const DATE_TIME_WITHOUT_SECONDS = /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}$/

function withSeconds (dateTime, seconds) {
    return DATE_TIME_WITHOUT_SECONDS.test(dateTime ?? '') ? `${dateTime}:${seconds}` : dateTime
}

/**
 * Month (YYYY-MM) before the one of the given date, the period that is usually invoiced
 */
export function getPreviousMonth (now = new Date()) {
    const month = new Date(now.getFullYear(), now.getMonth() - 1, 1)
    return `${month.getFullYear()}-${String(month.getMonth() + 1).padStart(2, '0')}`
}

/**
 * Start and end (YYYY-MM-DD HH:mm, as the date time inputs use) of the whole month (YYYY-MM)
 */
export function getMonthPeriod (month) {
    const [year, monthNumber] = month.split('-').map(Number)
    const lastDay = new Date(year, monthNumber, 0).getDate()
    return {
        start: `${month}-01 00:00`,
        end: `${month}-${String(lastDay).padStart(2, '0')} 23:59`
    }
}

/**
 * Invoice creation request of the form data: the whole month, or the custom start and end when
 * custom_period is set. The period has no seconds, the end includes its whole minute, so a month
 * ends at 23:59:59 as the invoices generated by the platform
 */
export function toInvoiceCreateData (formData) {
    const { start, end } = formData.custom_period
        ? { start: formData.period_start, end: formData.period_end }
        : getMonthPeriod(formData.period)
    return {
        customer_id: formData.customer_id,
        template_id: formData.template_id,
        period_start: withSeconds(start, '00'),
        period_end: withSeconds(end, '59')
    }
}

/**
 * The period filter sends the end without seconds (e.g. "2026-10-31 23:59"), which the API reads
 * as 23:59:00, while invoice periods can end within that minute (monthly ones at 23:59:59).
 * Extends the end to the last second of the selected minute, so those invoices are included.
 */
export function toInvoiceListFilter (filter) {
    const end = withSeconds(filter?.period_end_le, '59')
    if (end === filter?.period_end_le) {
        return filter
    }
    return {
        ...filter,
        period_end_le: end
    }
}
